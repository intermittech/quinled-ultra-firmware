"""Deterministic typed fixture inputs; capture bytes come from the real C emitter."""
import json,pathlib,sys
root=pathlib.Path(__file__).resolve().parents[1]
schema=json.loads((root/'tools/console_schema.json').read_text())
lines=['/* SPDX-License-Identifier: GPL-3.0-or-later', ' * Copyright (C) 2026 QuinLED */', '/* Generated by tools/gen_console_fixture.py. */','static void fixture(void) {']
expected=[]
for r in schema['records']:
    vals=[-((i+1)*17%((1<<(8*f['bytes']-1))-1)+1) if f['signed'] else ((i+1)*17)&((1<<(8*f['bytes']))-1) for i,f in enumerate(r['fields'])]
    if r['ctype']=='values':
        lines+=['{ const uint32_t v[]={'+','.join('(uint32_t)('+str(v)+')' for v in vals)+'}; console_record(output, 0, v, cf_'+r['record']+'); }']
    elif r['ctype'].startswith('uint'):
        lines+=['{ const '+r['ctype']+' v[]={'+','.join(str(v) for v in vals)+'}; console_record(output, 0, v, cf_'+r['record']+'); }']
    else:
        lines+=['{ '+r['ctype']+' v; memset(&v,0,sizeof(v));']
        lines+=['v.'+f['member']+'='+str(v)+';' for f,v in zip(r['fields'],vals)]
        lines+=['console_record(output, 0, &v, cf_'+r['record']+'); }']
    expected.append(dict(record=r['record'],index=0,fields={f['name']:v for f,v in zip(r['fields'],vals)}))
lines+=['}']
for name,content in [('test/console_fixture.inc','\n'.join(lines)+'\n'),('test/fixtures/console/expected.json',json.dumps(expected,indent=2)+'\n')]:
    p=root/name
    if '--check' in sys.argv:assert p.read_text()==content,'stale '+name
    else:p.write_text(content)
