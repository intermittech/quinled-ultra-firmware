"""Generate firmware-owned board facts, MCU pin bindings and build definitions.
Inputs: src/board/*/board.json and src/mcu/*/target.json. No central registry.
"""
import argparse
import copy
import json
from pathlib import Path
import shlex
import board_descriptor

FW = Path(__file__).resolve().parents[1]
SPDX = '/* SPDX-License-Identifier: GPL-3.0-or-later\n * Copyright (C) 2026 QuinLED */\n'
BANNER = SPDX + '/* Generated by tools/gen_targets.py; edit the owning src/board/<name>/board.json. */\n'


def definitions():
    boards = {p.parent.name: json.loads(p.read_text()) for p in sorted((FW/'src/board').glob('*/board.json'))}
    mcus = {p.parent.name: json.loads(p.read_text()) for p in sorted((FW/'src/mcu').glob('*/target.json'))}
    bindings = {}
    ids = set()
    for name, b in boards.items():
        if b['id'] in ids or not 1 <= b['id'] <= 254: raise ValueError('duplicate/invalid board ID')
        ids.add(b['id'])
        if not 1 <= len(b['product_name'].encode('utf8')) <= 63: raise ValueError('invalid product name')
        if b['id'] == 1 and (not b['link']['always_forwards'] or b['return'] or any('chain_port' in a for a in b['assemblies'])):
            raise ValueError('Dig2Analog always forwards and never returns; no chain assembly variant')
        for m, binding in b['bindings'].items():
            if m not in mcus or binding['board'] != name: raise ValueError('invalid binding')
            bindings[name+'-'+m] = binding
    return dict(boards=boards, mcus=mcus, bindings=bindings)


def generate(reg):
    files = {}
    for name, m in reg['mcus'].items():
        a = m.get('boot_api')
        if a is None: continue
        if not (0 <= a['table_offset'] and a['table_offset'] + 20 <= a['entry_offset_min'] <
                a['boot_bytes'] <= m['flash_bytes'] and
                all(a[k] % 4 == 0 for k in ('flash_base', 'link_base', 'table_offset', 'entry_offset_min', 'boot_bytes'))):
            raise ValueError('invalid boot API layout: '+name)
        banner = SPDX + '/* Generated from the owning MCU target.json by tools/gen_targets.py. */\n'
        h = banner + '#ifndef MCU_BOOT_API_LAYOUT_H\n#define MCU_BOOT_API_LAYOUT_H\n'
        for key, value in dict(FLASH_BASE=a['flash_base'], LINK_BASE=a['link_base'],
                               BOOT_BYTES=a['boot_bytes'], TABLE_OFFSET=a['table_offset'],
                               TABLE_ADDR=a['flash_base']+a['table_offset'],
                               ENTRY_MIN=a['flash_base']+a['entry_offset_min'],
                               ENTRY_END=a['flash_base']+a['boot_bytes']).items():
            h += f'#define MCU_BOOT_API_{key} 0x{value:08X}u\n'
        files[f'src/mcu/{name}/boot_api_layout.h'] = h + '#endif\n'
        files[f'src/mcu/{name}/boot_api_layout.ld'] = banner + (
            f'MCU_BOOT_LINK_BASE = 0x{a["link_base"]:X};\nMCU_BOOT_BYTES = 0x{a["boot_bytes"]:X};\n'
            f'MCU_BOOT_API_OFFSET = 0x{a["table_offset"]:X};\n' +
            (f'MCU_BOOT_RAM_BYTES = 0x{a["boot_ram_bytes"]:X};\n' if 'boot_ram_bytes' in a else ''))
    select = BANNER + '#ifndef BOARD_SELECT_H\n#define BOARD_SELECT_H\n#define BOARD_D2A_PLUS 1\n#define BOARD_UR_ANALOG_M 2\n#define BOARD_UR_DIGITAL_M 3\n#ifndef BOARD\n#define BOARD 1\n#endif\n'
    bindings = BANNER
    for i, (name, b) in enumerate(reg['boards'].items()):
        select += ('#if' if i == 0 else '#elif') + f' BOARD == {b["id"]}\n#include "{name}/board_gen.h"\n'
        facts = BANNER + f'#define BOARD_NAME "{name}"\n#define BOARD_PRODUCT_NAME "{b["product_name"]}"\n#define BOARD_LIGHTS {b["lights"]}u\n'
        for key, macro in [('pwm','BOARD_PWM'),('dline','BOARD_DLINE'),('return','BOARD_RETURN'),('channels','BOARD_CHANNELS'),('outputs','BOARD_OUTPUTS'),('hw_id','BOARD_HW_ID')]:
            facts += f'#define {macro} {b[key]}\n'
        facts += mcu_select(b, lambda o: f'#define BOARD_REVISION {o.get("revision", b["revision"])}u\n')
        facts += f'#define BOARD_VARIANT {b["default_assembly"]}u\n'
        facts += '#define BOARD_TESTJIG 1\n'
        facts += mcu_select(b, lambda o: f'#define BOARD_CALIBRATION_MS {o.get("calibration_ms", b["calibration_ms"])}u\n',
                            wanted=lambda o: 'calibration_ms' in o)
        assembly = next(a for a in b['assemblies'] if a['id']==b['default_assembly'])
        facts += f'#define BOARD_CHANNEL_RATING_MA {assembly.get("channel_ma",0)}u\n#define BOARD_OUTPUT_RATING_MA {b["output_rating_ma"]}u\n'
        for key, macro in [('fuse_ma','ISENSE_FUSE_MA'),('board_ma','ISENSE_BOARD_MA')]:
            facts += f'#define {macro} {b["current"][key]}u\n'
        facts += f'#ifndef ISENSE_MV_PER_A\n#define ISENSE_MV_PER_A {b["current"]["sense_mv_per_a"]}u\n#endif\n'
        facts += f'#define VSENSE_VREF_MV {b["voltage"]["vref_mv"]}u\n'
        for key, macro in [('supply_ratio','VSENSE_SUPPLY_RATIO_Q8'),('aux_ratio','VSENSE_AUX_RATIO_Q8')]:
            facts += f'#define {macro} {round(b["voltage"][key] * 256)}u\n'   # input voltage / pin voltage, Q8
        for k, pin in enumerate(b['jig_pads']):
            facts += f'#define BOARD_JIG_PAD_{k} "{pin}"\n'
        facts += '#define CH_R 0\n#define CH_G 1\n#define CH_B 2\n#define CH_W1 3\n#define CH_W2 4\n'

        files[f'src/board/{name}/board_gen.h'] = facts
        if b['return']:
            files[f'src/board/{name}/descriptor_gen.h'] = SPDX + mcu_select(b, lambda o: board_descriptor.header(
                bound_board(b, o)), wanted=lambda o: 'descriptor' in o or 'assemblies' in o or 'calibration_ms' in o)
    select += '#else\n#error "Unknown BOARD: no board/MCU binding"\n#endif\n#endif\n'
    files['src/board/boards.h'] = select
    for mcu in reg['mcus']:
        files[f'src/mcu/{mcu}/bindings.h'] = binding_header(reg, mcu)
    return files


def bound_board(board, overrides):
    """Physical assembly facts (and the calibration budget) may differ between MCU bindings of the same product."""
    b = copy.deepcopy(board)
    if 'calibration_ms' in overrides:
        b['calibration_ms'] = overrides['calibration_ms']
    if 'assemblies' in overrides:
        b['assemblies'] = copy.deepcopy(overrides['assemblies'])
        if b['default_assembly'] not in [a['id'] for a in b['assemblies']]:
            raise ValueError('binding lacks default assembly')
    return patched(b, overrides.get('descriptor'))


def patched(board, patch):
    """the board with a binding's descriptor patch applied (records: a dict, or every element of a list)"""
    if not patch:
        return board
    b = copy.deepcopy(board)
    for key, fields in patch.items():
        recs = b['descriptor'][key]
        for rec in (recs if isinstance(recs, list) else [recs]):
            rec.update(fields)
    return b


def mcu_select(b, text, wanted=lambda o: 'revision' in o):
    """text(overrides) for the default build, plus an MCU-selected variant for every binding that overrides it"""
    variants = [(m, binding.get('overrides', {})) for m, binding in b['bindings'].items()
                if wanted(binding.get('overrides', {}))]
    if not variants:
        return text({})
    out = ''
    for i, (m, o) in enumerate(variants):
        out += ('#if' if i == 0 else '#elif') + f' defined(MCU_{m.upper()}) && MCU_{m.upper()} == 1\n' + text(o)
    return out + '#else\n' + text({}) + '#endif\n'


def binding_header(reg, mcu):
    bindings = BANNER
    chosen = [v for v in reg['bindings'].values() if v['mcu'] == mcu]
    for i, binding in enumerate(chosen):
        b = reg['boards'][binding['board']]
        bindings += ('#if' if i == 0 else '#elif') + f' BOARD == {b["id"]}\n'
        bindings += f'#define ISENSE_ADC_CH {binding["adc"]["current"]}u\n#define VSENSE_SUPPLY_CH {binding["adc"]["supply"]}u\n'
        for j, uart in enumerate(binding['answer_uarts']):
            bindings += ('#if' if j == 0 else '#elif') + f' ANSWER_UART == {uart}\n'
            bindings += '#define MCU_BOARD_PINS \\\n'
            rows = binding['pins'][str(uart)]
            for k, row in enumerate(rows):
                port, pin, level, mode = row
                bindings += f'    MCU_PIN({port}, {pin}, {level}, {mode}),' + (' \\\n' if k < len(rows)-1 else '\n')
        bindings += '#else\n#error "ANSWER_UART: no binding for this board"\n#endif\n'
    bindings += '#else\n#error "No board/MCU binding"\n#endif\n'
    return bindings


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--board', default='1')
    ap.add_argument('--mcu', default='ch32v20x')
    ap.add_argument('--shell', action='store_true')
    args = ap.parse_args()
    reg = definitions()
    boards = [b for n,b in reg['boards'].items() if args.board in (str(b['id']), n)]
    binding = next((v for v in reg['bindings'].values() if v['mcu']==args.mcu and reg['boards'][v['board']] in boards),None)
    if not binding: ap.error('no binding for BOARD=%s MCU=%s' % (args.board,args.mcu))
    if args.shell:
        m = reg['mcus'][args.mcu]; b = reg['boards'][binding['board']]
        # binding features (board.json bindings.<mcu>.features): fx_v407 = the V407 Digital-M effects layer (src/core/fx_v407);
        # lean_telemetry = no DIAG page, POWER events or SUPPLY page (the V203 Digital-M: core/vdip.h LEAN_TELEMETRY)
        feat = binding.get('features', {})
        for k,v in {'TARGET_BOARD':b['id'], 'TARGET_MCU':args.mcu,'TARGET_DEFINE':m['define'], 'TARGET_STARTUP':m['startup'],'TARGET_LINKER':m['linker'],'TARGET_APP_LINKER':m['app_linker'],'TARGET_HAL':'src/mcu/'+args.mcu,'TARGET_FX_V407':int(bool(feat.get('fx_v407',0))),'TARGET_LEAN_TELEMETRY':int(bool(feat.get('lean_telemetry',0)))}.items():
            print(k+'='+shlex.quote(str(v)))
        return
    for rel, content in generate(reg).items():
        p = FW / rel
        if args.check:
            if not p.exists() or p.read_text()!=content: raise SystemExit('stale generated file: '+rel)
        else:
            p.parent.mkdir(parents=True,exist_ok=True); p.write_text(content, newline='\n')

if __name__=='__main__': main()
