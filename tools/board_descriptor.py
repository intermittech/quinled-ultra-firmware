"""Encode board-owned physical facts as protocol descriptor format 1 TLVs."""
import math
import struct
SCHEMAS = {
 'link': (1, '>BBBH BH BBBB HBBB'.replace(' ',''), 'port flags rates delay_ns width_ns gap_us late_us clock kind phy mtu reply reserved profiles'),
 'domains': (2, '>BBHHHHBBB', 'id_parent kind min_10mv max_10mv rating_ma trip_ma enforcement sense efficiency'),
 'pwm': (3, '>BBBBHHBHB', 'first count domain flags channel_ma bank_ma enforcement cal_ms reserved'),
 'pixel': (4, '>BBBBHHHHHHHHHBBHHHB', 'output domain segments flags frame_bytes rgb rgbw rgbcct bit_ns delay_us chips rating_ma fps enforcement sources ingresses cal_ms latch_us control'),
 'senses': (5, '>BBBBBbH', 'id quantity domain target flags exponent full_scale'),
 'resources': (7, '>HHIIBB', 'pool simultaneous local_bytes_s stream_bytes_s outputs calibrations'),
}
def crc16(data):
    crc=65535
    for byte in data:
        crc^=byte<<8
        for _ in range(8): crc=((crc<<1)^ (0x1021 if crc&32768 else 0))&65535
    return crc

def resolver(board):
    facts=dict(board,assembly=next(a for a in board['assemblies'] if a['id']==board['default_assembly']))
    def resolve(value):
        if not isinstance(value,str):return value
        if not value.startswith('$'):raise ValueError('invalid fact reference')
        result=facts
        for key in value[1:].split('.'):result=result[key]
        return result
    return resolve

def input_wh(board):
    """the LIFE_SYNC energy step's Wh per 0.1 h, exact, as num / den in lowest terms: root domain 0's continuous rating
    (mA) x maximum voltage (10 mV) / 10^6 (10 uW x 0.1 h = 1 uWh); (0, 1) when either is unknown (0xFFFF) or there is no
    domain 0. The receiver computes (num x (0.1 h + 10) + den - 1) / den in 32 bits, 0.1 h up to 7,200 (core/energy.h)"""
    resolve=resolver(board)
    p=0
    for d in board['descriptor'].get('domains',[]):
        if resolve(d['id_parent'])>>4==0:
            ma,v=resolve(d['rating_ma']),resolve(d['max_10mv'])
            p=0 if 65535 in (ma,v) else ma*v
    g=math.gcd(p,1000000)
    num,den=p//g,1000000//g
    if num*7210+den-1>=1<<32:
        raise ValueError('input rating x voltage: the LIFE_SYNC energy step %d/%d Wh per 0.1 h exceeds 32 bits'%(num,den))
    return num,den

def encode(board):
    resolve=resolver(board)
    records=[]
    for key,(tag,fmt,fields) in SCHEMAS.items():
        values=board['descriptor'].get(key,[])
        if isinstance(values,dict):values=[values]
        for record in values:
            payload=struct.pack(fmt,*(resolve(record[name]) for name in fields.split()))
            records.append(bytes([tag,len(payload)])+payload)
    # Descriptor text uses the short display name; product_name is the full name.
    name=board.get('descriptor_product_name', board['product_name']).encode('utf8')
    records.append(bytes([8,len(name)])+name)
    body=b''.join(records)
    header=bytearray([1,11,0,0,0,0,board['id'],board['lights'],len(records),0,board['default_assembly']])
    blob=header+body
    if len(blob)>6144:raise ValueError('descriptor exceeds transport')
    blob[2:4]=len(blob).to_bytes(2,'big');blob[4:6]=crc16(blob[6:]).to_bytes(2,'big')
    return bytes(blob)

def header(board):
    blob=encode(board)
    return '/* Generated by tools/gen_targets.py from this board.json. */\n' + \
        f'#define BOARD_DESCRIPTOR_BYTES {len(blob)}u\n#define BOARD_DESCRIPTOR_CRC 0x{int.from_bytes(blob[4:6],"big"):04X}u\n' + \
        '#define BOARD_IN_WH_NUM %du\n#define BOARD_IN_WH_DEN %du\n'%input_wh(board) + \
        'static const unsigned char board_descriptor[BOARD_DESCRIPTOR_BYTES] = {\n'+ \
        '\n'.join('    '+', '.join(f'0x{x:02x}' for x in blob[i:i+16])+',' for i in range(0,len(blob),16))+'\n};\n'
