"""Generate src/core/ultra_tables.c: the fixed-point polynomials of the exact gamma (x^g = 2^(g log2 x)) and a sine
quarter-wave table for the breathe / colour effects.

Both polynomials have only non-negative coefficients, so ultra_gamma's Horner steps (each product floored) are
monotonic by construction, at every 32-bit input:
  - log2(1 + t) = 1 - q(u), u = 1 - t, q(u) = a1 u + ... + a7 u^7: non-negative least squares (scipy), a1..a7 >= 0,
    their sum exactly 1 (Q29), so q(1) = 1 and the curve meets the next power of two;
  - 2^t = 1 + c1 t + ... + c5 t^5: least squares with the end points exact (p(0) = 1, p(1) = 2), Q30, all positive.
Errors: log2 1.2e-6, exp2 1.1e-7 -> within 0.7 counts of pow() for gamma 0.45..3 and within 1 count of the former
257-point tables at every 32-bit input (test/test_gamma_tables.c samples it)."""
import math
import os

import numpy as np
from scipy.optimize import nnls

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "core", "ultra_tables.c")
LOG2_DEG, EXP2_DEG = 7, 5
QL, QE = 29, 30


def nodes(n=6000):
    k = np.arange(n)
    return (1 - np.cos((2 * k + 1) / (2 * n) * np.pi)) / 2      # Chebyshev nodes on [0, 1]


def fit_log2():
    u = nodes()
    a, _ = nnls(np.vander(u, LOG2_DEG + 1, increasing=True)[:, 1:], 1 - np.log2(2 - u))
    c = [round(x * 2 ** QL) for x in a]
    c[0] += (1 << QL) - sum(c)                                   # q(1) = 1 exactly
    assert all(x >= 0 for x in c)
    return c                                                     # a1 .. a7


def fit_exp2():
    t = nodes()
    w = t * (1 - t)
    y = (np.exp2(t) - 1 - t) / w                                 # 2^t = 1 + t + t (1 - t) r(t)
    r, *_ = np.linalg.lstsq(np.vander(t, EXP2_DEG - 1, increasing=True) * w[:, None], y * w, rcond=None)
    p = [0.0] * (EXP2_DEG + 1)
    p[0], p[1] = 1.0, 1.0
    for i, c in enumerate(r):
        p[i + 1] += c
        p[i + 2] -= c
    c = [round(x * 2 ** QE) for x in p]
    c[0] = 1 << QE
    c[1] += (2 << QE) - sum(c)                                   # p(1) = 2 exactly
    assert all(x > 0 for x in c)
    return c                                                     # c0 .. c5


log2_poly = fit_log2()
exp2_poly = fit_exp2()
sin_tab = [round(math.sin(math.pi / 2 * i / 64) * 65535) for i in range(65)]   # quarter wave, Q16

lines = ["/* generated by tools/gen_ultra_tables.py */", '#include "ultra.h"', "",
         "/* log2(1 + t) = 1 - q(1 - t), q(u) = a1 u + ... + a7 u^7, Q29, a1 first (ultra_gamma) */",
         "const uint32_t ultra_log2_poly[%d] = { %s };" % (len(log2_poly), ", ".join("%du" % c for c in log2_poly)),
         "/* 2^t = c0 + c1 t + ... + c5 t^5, Q30, c0 first */",
         "const uint32_t ultra_exp2_poly[%d] = { %s };" % (len(exp2_poly), ", ".join("%du" % c for c in exp2_poly)), "",
         "const uint16_t ultra_sin_tab[65] = {"]
for k in range(0, 65, 13):
    lines.append("    " + ", ".join("%5d" % v for v in sin_tab[k:k + 13]) + ",")
lines += ["};", ""]
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("wrote", OUT)
