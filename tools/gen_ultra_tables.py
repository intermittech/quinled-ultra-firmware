"""Generate src/core/ultra_tables.c: fixed-point log2 / exp2 tables for the exact gamma (x^g) and a sine
quarter-wave table for the breathe / colour effects."""
import math
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "core", "ultra_tables.c")


def arr(name, vals, ctype="uint32_t", per=8):
    lines = ["const %s %s[%d] = {" % (ctype, name, len(vals))]
    for k in range(0, len(vals), per):
        lines.append("    " + ", ".join("0x%08Xu" % v if ctype == "uint32_t" else "%5d" % v for v in vals[k:k + per]) + ",")
    lines.append("};")
    return lines


log2_tab = [min(0xFFFFFFFF, round(math.log2(1 + i / 256) * 2**31)) for i in range(257)]   # Q31, [0, 1]
exp2_tab = [min(0xFFFFFFFF, round(2 ** (i / 256) * 2**30)) for i in range(257)]           # 2^f * 2^30
sin_tab = [round(math.sin(math.pi / 2 * i / 64) * 65535) for i in range(65)]               # quarter wave, Q16

lines = ["/* generated by tools/gen_ultra_tables.py */", '#include "ultra.h"', ""]
lines += arr("ultra_log2_tab", log2_tab) + [""]
lines += arr("ultra_exp2_tab", exp2_tab) + [""]
lines += arr("ultra_sin_tab", sin_tab, "uint16_t", 13) + [""]
open(OUT, "w", encoding="utf-8").write("\n".join(lines))
print("wrote", OUT)
