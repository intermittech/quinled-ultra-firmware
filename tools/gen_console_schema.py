"""Generate compact native record walks from the sole diagnostic schema."""
import json, pathlib, re, sys
root=pathlib.Path(__file__).resolve().parents[1]
s=json.loads((root/'tools/console_schema.json').read_text())
assert 0<s['schema']<256
assert len({r['record'] for r in s['records']})==len(s['records'])
fmt='/* SPDX-License-Identifier: GPL-3.0-or-later\n * Copyright (C) 2026 QuinLED */\n/* Generated by tools/gen_console_schema.py. */\n#define CONSOLE_SCHEMA_HEX "'+format(s['schema'],'02X')+'"\n#define CONSOLE_LINE_MAX '+str(s['max_line_bytes'])+'u\n'
lines=['/* SPDX-License-Identifier: GPL-3.0-or-later', ' * Copyright (C) 2026 QuinLED */', '/* Generated by tools/gen_console_schema.py. Do not edit. */']
digital_records=[]
for r in s['records']:
    fs=r['fields']; rid=r['record']; scalar=r['ctype']=='values' or r['ctype'].startswith('uint')
    if r.get('condition'):lines.append('#if '+r['condition'])
    if r['ctype']=='values': lines.append('#if defined(CONSOLE_UR_DIGITAL_M)')
    offsets=[str(sum(f['bytes'] for f in fs[:i])) if scalar else 'offsetof('+r['ctype']+', '+f['member']+')' for i,f in enumerate(fs)]
    for i,f in enumerate(fs):
        checks='sizeof('+r['ctype']+')<4096' if not scalar else '1'
        if not scalar: checks+=' && sizeof((('+r['ctype']+' *)0)->'+f['member']+')=='+str(f['bytes'])
        lines.append('typedef char console_width_'+rid+'_'+str(i)+'[('+checks+')?1:-1];')
    runs=[];i=0
    while i<len(fs):
        j=i+1
        while j<len(fs) and j-i<4 and fs[j]['bytes']==fs[i]['bytes']:
            if not scalar:
                # Only arrays are coalesced automatically. Native flat spans can
                # be named in the schema and are checked by the C compiler.
                a=re.fullmatch(r'(.*)\[(\d+)\]',fs[i]['member']); b=re.fullmatch(r'(.*)\[(\d+)\]',fs[j]['member'])
                if not (a and b and a[1]==b[1] and int(b[2])==int(a[2])+j-i) and not any(i>=span[0] and j<span[0]+span[1] for span in r.get('spans',[])): break
                lines.append('#if defined(__GNUC__)\ntypedef char console_span_'+rid+'_'+str(j)+'[('+offsets[j]+'=='+offsets[i]+'+'+str((j-i)*fs[i]['bytes'])+')?1:-1];\n#endif')
            j+=1
        w={1:0,2:1,4:2}[fs[i]['bytes']]
        runs.append('(uint16_t)('+offsets[i]+' + ('+str(j-i-1)+'u << 12) + ('+str(w)+'u << 14))');i=j
    lines.append('static const uint16_t cf_'+rid+'[] = { '+str(ord(rid)*256+len(runs))+', '+', '.join(runs)+' };')
    assert 17+sum(1+2*f['bytes'] for f in fs)<=s['max_line_bytes'],rid
    if r['ctype']=='values':lines.append('#endif')
    if r.get('condition'):lines.append('#endif')
    if r.get('ud_emit'):
        body=''
        if r['ctype']=='values': body='const uint32_t v[]={'+','.join('(uint32_t)('+f['expr']+')' for f in fs)+'}; '
        body+='console_record(uart_write, 0, '+('v' if r['ctype']=='values' else r['base'])+', cf_'+rid+');'
        digital_records.append('static void con_'+rid+'(void) { '+body+' }')
ev=['/* SPDX-License-Identifier: GPL-3.0-or-later', ' * Copyright (C) 2026 QuinLED */', '/* Generated by tools/gen_console_schema.py. */']+['#define CZ_'+e['name']+' '+str(e['value']) for e in s['events']]
for rel,content in [('src/core/console_format.h',fmt),('src/core/console_fields.inc','\n'.join(lines)+'\n'),('src/core/console_events.h','\n'.join(ev)+'\n'),('src/app/console_ur_digital_m.inc','\n'.join(['/* SPDX-License-Identifier: GPL-3.0-or-later', ' * Copyright (C) 2026 QuinLED */', '/* Generated by tools/gen_console_schema.py. */']+digital_records)+'\n')]:
    p=root/rel
    if '--check' in sys.argv: assert p.read_text()==content, 'stale '+rel
    else:p.write_text(content)
